"""Generate internal/capture/exe_steam_table.go: the Steam -> retail vtable map for Steam captures.
Usage: python gen_steam_vtables.py <r302_steam_vtables.json> <builder_go>/internal/capture/exe_steam_table.go
Input: the maintainer's r302 table ({"exe": {steam_sha256, retail_sha256}, "vtables": {steam: retail}, "unresolved": []}),
every entry mapped by reference signatures + a slot-by-slot vtable check of both executables. Refuses an unresolved or
non-injective table, or a Steam key that is also a retail value.
"""
import json
import sys
from pathlib import Path


def main():
    src, out = sys.argv[1], sys.argv[2]
    j = json.loads(Path(src).read_text(encoding='utf-8'))
    if j.get('unresolved'):
        sys.exit('unresolved entries: %r' % j['unresolved'])
    m = {int(k, 16): int(v, 16) for k, v in j['vtables'].items()}
    if len(set(m.values())) != len(m):
        sys.exit('table is not injective')
    if set(m) & set(m.values()):
        sys.exit('a Steam key equals a retail value')
    exe = j['exe']
    lines = ['// Code generated by gen/gen_steam_vtables.py; DO NOT EDIT.',
             '// Source: the r302 Steam -> retail vtable table (%d entries, all confirmed by reference signatures and a' % len(m),
             '// slot-by-slot vtable comparison of the two executables).',
             '', 'package capture', '',
             '// SHA-256 of the two supported BFBC2Game.exe builds (the .bc2raw header ExeSHA256).',
             'const (',
             '\tExeRetailSHA256 = "%s"' % exe['retail_sha256'],
             '\tExeSteamSHA256  = "%s"' % exe['steam_sha256'],
             ')', '',
             '// steamToRetail maps every vtable a Steam capture records to its retail value.',
             'var steamToRetail = map[uint32]uint32{']
    for k in sorted(m):
        lines.append('\t0x%07x: 0x%07x,' % (k, m[k]))
    lines.append('}')
    Path(out).write_text('\n'.join(lines) + '\n', encoding='ascii', newline='\n')
    print(len(m), 'entries ->', out)


if __name__ == '__main__':
    main()
