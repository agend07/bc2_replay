"""Generate internal/pyc/nfkd_table.go: per code point, the ASCII part of unicodedata.normalize('NFKD', ch).
Usage: <oracle>/python.exe gen_nfkd_table.py <builder_go>/internal/pyc/nfkd_table.go
A per-code-point table is exact for NFKD -> ascii-ignore: decomposition is per code point and canonical reordering only
moves marks with a non-zero combining class, which are never ASCII. Code points absent from the table yield ''.
"""
import sys
import unicodedata
from pathlib import Path


def main():
    cps, blob, offs = [], [], [0]
    for cp in range(0x80, 0x110000):
        if 0xD800 <= cp <= 0xDFFF: continue
        a = unicodedata.normalize('NFKD', chr(cp)).encode('ascii', 'ignore').decode('ascii')
        if a:
            cps.append(cp); blob.append(a); offs.append(offs[-1] + len(a))
    s = ''.join(blob)
    lines = ['// Code generated by gen/gen_nfkd_table.py; DO NOT EDIT.',
             '// Source: frozen oracle CPython %s, unicodedata.unidata_version %s.' % (sys.version.split()[0], unicodedata.unidata_version),
             '', 'package pyc', '',
             '// nfkdUnidataVersion is the Unicode database version the table was generated from.',
             'const nfkdUnidataVersion = "%s"' % unicodedata.unidata_version, '',
             '// nfkdCP lists the non-ASCII code points whose NFKD decomposition contains ASCII, ascending.',
             'var nfkdCP = [...]uint32{']
    for i in range(0, len(cps), 12):
        lines.append('\t' + ' '.join('0x%x,' % c for c in cps[i:i + 12]))
    lines += ['}', '', '// nfkdOff[i]:nfkdOff[i+1] slices nfkdASCII for nfkdCP[i].', 'var nfkdOff = [...]uint32{']
    for i in range(0, len(offs), 16):
        lines.append('\t' + ' '.join('%d,' % o for o in offs[i:i + 16]))
    lines += ['}', '', '// nfkdASCII is the concatenated ASCII output.', 'const nfkdASCII = "" +']
    chunks = [s[i:i + 96] for i in range(0, len(s), 96)] or ['']
    for i, c in enumerate(chunks):
        lit = '"' + c.replace('\\', '\\\\').replace('"', '\\"') + '"'
        lines.append('\t' + lit + (' +' if i < len(chunks) - 1 else ''))
    Path(sys.argv[1]).write_text('\n'.join(lines) + '\n', encoding='ascii', newline='\n')
    print(len(cps), 'code points,', len(s), 'bytes, unidata', unicodedata.unidata_version)


if __name__ == '__main__':
    main()
